// Regenerates src/fonts.css from @fontsource/zen-kaku-gothic-new: woff2 only, unicode-range split,
// weights 400/500/700, files referenced from node_modules.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', '@fontsource', 'zen-kaku-gothic-new');
const out = ['/* Generated by scripts/gen-fonts-css.mjs. Zen Kaku Gothic New, SIL OFL 1.1 (see THIRD-PARTY-NOTICES.txt). */'];
for (const w of [400, 500, 700]) {
  const css = readFileSync(join(pkg, `${w}.css`), 'utf8');
  for (const block of css.match(/@font-face\s*\{[^}]*\}/g) ?? []) {
    const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
    if (!file) throw new Error(`no woff2 in a ${w} face`);
    out.push(block.replace(/src:[^;]+;/, `src: url(../node_modules/@fontsource/zen-kaku-gothic-new/files/${file}) format('woff2');`));
  }
}
writeFileSync(join(root, 'src', 'fonts.css'), out.join('\n') + '\n');
console.log(`src/fonts.css: ${out.length - 1} faces`);
